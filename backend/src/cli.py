async def _analyze_one(*, chart, from_version, to_version, values,
                       repo_url=None, repo_name=None, wrapper_key=None):
    """Pull both versions, render, diff. Returns (stats, changes). Raises RuntimeError on failure."""
    await ensure_helm_ready()

    # A short repo name means register it (`helm repo add`) and address as repo/chart;
    # otherwise the repo URL (from a Chart.yaml dependency) is passed straight to pull.
    if repo_name and repo_url:
        await repo_add(repo_name, repo_url)
        repo_url = None

    old_dir = await pull_chart(chart, from_version, repo_url)
    new_dir = await pull_chart(chart, to_version, repo_url)

    values_path = Path(values)
    if not values_path.exists():
        raise RuntimeError(f"Values file not found: {values_path}")
    values_yaml = values_path.read_text()
    user_top = yaml.safe_load(values_yaml) or {}

    wrapper     = wrapper_key or detect_wrapper(user_top, old_dir / "values.yaml")
    values_text = yaml.safe_dump(
        unwrap_values(values_yaml, wrapper), default_flow_style=False, sort_keys=False
    ) if wrapper else values_yaml

    tmp = tempfile.NamedTemporaryFile(
        mode="w", suffix=".yaml", delete=False, dir="/tmp", prefix="chartsmith_"
    )
    tmp.write(values_text); tmp.flush(); tmp.close()
    values_file = Path(tmp.name)
    try:
        old_manifests = await helm_template(old_dir, values_file)
        new_manifests = await helm_template(new_dir, values_file)
    finally:
        values_file.unlink(missing_ok=True)

    for label, manifests in ((from_version, old_manifests), (to_version, new_manifests)):
        if manifests.startswith("# RENDER ERROR"):
            raise RuntimeError(f"helm template failed for {label}:\n{manifests}")

    # Diff engine prints [INFO]/[DEBUG] to stdout — route to stderr to keep stdout clean.
    with contextlib.redirect_stdout(sys.stderr):
        changes = compare_manifests(old_manifests, new_manifests)
    return compute_stats(changes), changes


async def _cmd_analyze(args: argparse.Namespace) -> int:
    try:
        stats, changes = await _analyze_one(
            chart=args.chart, from_version=args.from_version, to_version=args.to_version,
            values=args.values, repo_url=args.repo_url, repo_name=args.repo_name,
            wrapper_key=args.wrapper_key,
        )
    except (RuntimeError, yaml.YAMLError) as e:
        print(f"[ERROR] {e}", file=sys.stderr)
        return EXIT_ERROR

    if args.format == "json":
        print(json.dumps({
            "chart":        args.chart,
            "from_version": args.from_version,
            "to_version":   args.to_version,
            "stats":        stats,
            "changes":      changes,
        }, indent=2))
    elif args.format == "markdown":
        print(_format_markdown(
            args.chart, args.from_version, args.to_version,
            stats, changes, args.fail_on,
        ))
    elif args.format == "html":
        print(_format_html(
            args.chart, args.from_version, args.to_version,
            stats, changes, args.fail_on,
        ))
    else:  # text
        print(f"ChartSmith: {args.chart}  {args.from_version} → {args.to_version}")
        print(f"Changes: {stats['total_changes']}  "
              f"critical={stats['critical']}  high={stats['high']}  "
              f"medium={stats['medium']}  safe={stats['safe']}")
        for c in changes:
            print(f"  [{c['severity'].upper():8}] {c['kind']}/{c['name']} — {c['change_type']}")

    return EXIT_BLOCKED if _blocked(changes, args.fail_on) else EXIT_PASS


