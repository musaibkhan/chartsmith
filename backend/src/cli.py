def _detect_platform() -> str:
    if os.getenv("GITHUB_ACTIONS") == "true":
        return "github"
    if os.getenv("GITLAB_CI") == "true":
        return "gitlab"
    return "local"


def _git(*a: str) -> str:
    return subprocess.run(["git", *a], capture_output=True, text=True).stdout.strip()


def _resolve_refs(args, platform: str) -> tuple[str, str]:
    if args.base_ref:
        return args.base_ref, (args.head_ref or "HEAD")
    if platform == "gitlab":
        base   = os.getenv("CI_MERGE_REQUEST_DIFF_BASE_SHA", "")
        head   = os.getenv("CI_COMMIT_SHA", "HEAD")
        target = os.getenv("CI_MERGE_REQUEST_TARGET_BRANCH_NAME", "")
        if not base and target:
            _git("fetch", "origin", target)
            base = _git("merge-base", f"origin/{target}", "HEAD")
        return (base or "HEAD~1"), head
    if platform == "github":
        head   = os.getenv("GITHUB_SHA", "HEAD")
        target = os.getenv("GITHUB_BASE_REF", "")   # PR target branch
        base = ""
        if target:
            _git("fetch", "origin", target)
            base = _git("merge-base", f"origin/{target}", "HEAD")
        return (base or "HEAD~1"), head
    return "HEAD~1", "HEAD"


def _gitlab_artifact_url(out_path: str) -> str | None:
    proj = os.getenv("CI_PROJECT_PATH")
    job  = os.getenv("CI_JOB_ID")
    if not proj or not job:
        return None
    top, _, rest = proj.partition("/")
    domain = os.getenv("CI_PAGES_DOMAIN", "gitlab.io")
    return f"https://{top}.{domain}/-/{rest}/-/jobs/{job}/artifacts/{out_path}"


def _post_gitlab_comment(body: str) -> bool:
    # Prefer an explicitly API-scoped token; CI_JOB_TOKEN can't post notes.
    token = os.getenv("GITLAB_API_TOKEN") or os.getenv("GITLAB_TOKEN")
    mr    = os.getenv("CI_MERGE_REQUEST_IID")
    proj  = os.getenv("CI_PROJECT_ID")
    api   = os.getenv("CI_API_V4_URL", "https://gitlab.com/api/v4")
    if not (token and mr and proj):
        return False
    base = f"{api}/projects/{proj}/merge_requests/{mr}/notes"
    hdr  = {"PRIVATE-TOKEN": token}
    req  = urllib.request.Request(f"{base}?per_page=100", headers=hdr)
    for note in json.load(urllib.request.urlopen(req, timeout=15)):
        if note["body"].startswith("## ChartSmith"):
            urllib.request.urlopen(urllib.request.Request(
                f"{base}/{note['id']}", method="DELETE", headers=hdr), timeout=15)
    data = urllib.parse.urlencode({"body": body}).encode()
    urllib.request.urlopen(urllib.request.Request(base, data=data, method="POST", headers=hdr), timeout=15)
    return True


def _post_github_comment(body: str) -> bool:
    token = os.getenv("GITHUB_TOKEN")
    repo  = os.getenv("GITHUB_REPOSITORY")
    api   = os.getenv("GITHUB_API_URL", "https://api.github.com")
    ref   = os.getenv("GITHUB_REF", "")
    pr    = ref.split("/")[2] if ref.startswith("refs/pull/") else os.getenv("PR_NUMBER", "")
    if not (token and repo and pr):
        return False
    base = f"{api}/repos/{repo}/issues/{pr}/comments"
    hdr  = {"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json",
            "User-Agent": "chartsmith"}
    req  = urllib.request.Request(f"{base}?per_page=100", headers=hdr)
    for c in json.load(urllib.request.urlopen(req, timeout=15)):
        if c.get("body", "").startswith("## ChartSmith"):
            urllib.request.urlopen(urllib.request.Request(
                c["url"], method="DELETE", headers=hdr), timeout=15)
    h = dict(hdr); h["Content-Type"] = "application/json"
    data = json.dumps({"body": body}).encode()
    urllib.request.urlopen(urllib.request.Request(base, data=data, method="POST", headers=h), timeout=15)
    return True


async def _cmd_ci(args: argparse.Namespace) -> int:
    platform = _detect_platform()
    base, head = _resolve_refs(args, platform)
    print(f"[ci] platform={platform} base={base} head={head}", file=sys.stderr)

    bumps = detect_bumps_from_git(base_ref=base, head_ref=head, search_path=args.path)
    if not bumps:
        print("No chart version bumps detected — nothing to analyse.")
        return EXIT_PASS

    outdir = Path(args.output_dir)
    outdir.mkdir(parents=True, exist_ok=True)

    blocked_any = err_any = False
    results = []   # (bump, out_path, stats, changes)

    for b in bumps:
        src_dir = os.path.dirname(b.get("source_file", ""))
        values  = os.path.join(src_dir, args.values_file) if src_dir else args.values_file
        print(f"==> {b['chart']} {b['from_version']} -> {b['to_version']} (values: {values})")
        if not os.path.exists(values):
            print(f"   [skip] no values file at {values}")
            continue
        try:
            stats, changes = await _analyze_one(
                chart=b["chart"], from_version=b["from_version"], to_version=b["to_version"],
                values=values, repo_url=b.get("repo_url"), repo_name=b.get("repo_name"),
                wrapper_key=b.get("wrapper_key"),
            )
        except (RuntimeError, yaml.YAMLError) as e:
            print(f"   [error] {e}", file=sys.stderr)
            err_any = True
            continue

        html = _format_html(b["chart"], b["from_version"], b["to_version"], stats, changes, args.fail_on)
        out  = outdir / f"chartsmith-{b['chart'].replace('/', '-')}.html"
        out.write_text(html)
        results.append((b, out, stats, changes))
        if _blocked(changes, args.fail_on):
            blocked_any = True
        print(f"   critical={stats['critical']} high={stats['high']} "
              f"medium={stats['medium']} safe={stats['safe']} -> {out}")

    # ── always surface report locations in the job log ───────────────────────
    if results:
        print("\nReports:")
        for b, out, stats, _ in results:
            url = _gitlab_artifact_url(str(out)) if platform == "gitlab" else None
            loc = url or str(out)
            print(f"  • {b['chart']} {b['from_version']} → {b['to_version']} "
                  f"(risk {_risk_label(stats)}) — {loc}")

    # ── publish comment (best-effort; never fail the job on a comment error) ──
    if results and not args.no_comment:
        try:
            if platform == "gitlab":
                lines = []
                for b, out, stats, _ in results:
                    url   = _gitlab_artifact_url(str(out))
                    label = f"{b['chart']} `{b['from_version']} → {b['to_version']}` · risk {_risk_label(stats)}"
                    lines.append(f"- **{label}** — [📊 Open report]({url})" if url else f"- **{label}**")
                body = "## ChartSmith\n\nRendered upgrade analysis (opens in a new tab):\n\n" + "\n".join(lines)
                print("\n📝 Posted ChartSmith links to MR." if _post_gitlab_comment(body)
                      else "\n[info] GITLAB_TOKEN/MR context missing — comment skipped (links above).")
            elif platform == "github":
                # GitHub renders markdown comments richly — post the full report inline.
                parts = [_format_markdown(b["chart"], b["from_version"], b["to_version"], stats, changes, args.fail_on)
                         for b, _, stats, changes in results]
                body = "## ChartSmith\n\n" + "\n\n---\n\n".join(parts)
                print("\n📝 Posted ChartSmith report to PR." if _post_github_comment(body)
                      else "\n[info] GITHUB_TOKEN/PR context missing — comment skipped (reports above).")
        except Exception as e:
            print(f"\n[warn] comment posting failed ({e}) — report links are listed above.", file=sys.stderr)

    return EXIT_BLOCKED if blocked_any else (EXIT_ERROR if err_any else EXIT_PASS)


def _cmd_detect_bump(args: argparse.Namespace) -> int:
    bumps = detect_bumps_from_git(
        base_ref=args.base_ref,
        head_ref=args.head_ref,
        search_path=args.path,
    )

    if args.format == "env":
        if not bumps:
            print("CHARTSMITH_BUMPS_FOUND=false")
        else:
            b = bumps[0]
            print("CHARTSMITH_BUMPS_FOUND=true")
            print(f"CHARTSMITH_CHART={b['chart']}")
            print(f"CHARTSMITH_FROM={b['from_version']}")
            print(f"CHARTSMITH_TO={b['to_version']}")
            if b.get("repo_name"):
                print(f"CHARTSMITH_REPO_NAME={b['repo_name']}")
            if b.get("repo_url"):
                print(f"CHARTSMITH_REPO_URL={b['repo_url']}")
            if b.get("wrapper_key"):
                print(f"CHARTSMITH_WRAPPER_KEY={b['wrapper_key']}")
    else:
        print(json.dumps(bumps, indent=2))

    return EXIT_PASS


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="chartsmith",
        description="Helm upgrade advisor — forecast breaking changes before you upgrade.",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    # ── analyze ──────────────────────────────────────────────────────────────
    a = sub.add_parser("analyze", help="Diff two chart versions against your values.yaml")
    a.add_argument("--chart",        required=True,
                   help="Chart name, e.g. grafana-community/loki")
    a.add_argument("--from-version", required=True, dest="from_version")
    a.add_argument("--to-version",   required=True, dest="to_version")
    a.add_argument("--values",       required=True,
                   help="Path to your values.yaml (or - for stdin)")
    a.add_argument("--repo-name",    dest="repo_name", default=None,
                   help="Helm repo short name (added via helm repo add)")
    a.add_argument("--repo-url",     dest="repo_url", default=None,
                   help="Helm repo URL")
    a.add_argument("--context",      default="plain",
                   choices=["plain", "argocd", "umbrella", "helmfile"])
    a.add_argument("--wrapper-key",  dest="wrapper_key", default=None,
                   help="ArgoCD/umbrella wrapper key (auto-detected if omitted)")
    a.add_argument("--fail-on",      dest="fail_on", default="critical",
                   choices=["none", "critical", "high", "medium", "safe"],
                   help="Exit 1 when changes at this severity or above are found")
    a.add_argument("--format",       default="markdown",
                   choices=["markdown", "json", "text", "html"])

    # ── detect-bump ──────────────────────────────────────────────────────────
    d = sub.add_parser(
        "detect-bump",
        help="Detect Helm chart version bumps in a git diff (Chart.yaml, ArgoCD, helmfile)",
    )
    d.add_argument("--base-ref", required=True, dest="base_ref",
                   help="Base git ref (e.g. $CI_MERGE_REQUEST_DIFF_BASE_SHA)")
    d.add_argument("--head-ref", default="HEAD", dest="head_ref",
                   help="Head git ref (default: HEAD)")
    d.add_argument("--path",     default=".",
                   help="Directory to search within (default: .)")
    d.add_argument("--format",   default="json", choices=["json", "env"],
                   help="json = structured list; env = shell-sourceable KEY=VALUE")

    # ── ci ────────────────────────────────────────────────────────────────────
    c = sub.add_parser(
        "ci",
        help="One-shot CI driver: detect bumps in the MR/PR, analyse each, write HTML "
             "reports, and post a comment. Auto-detects GitLab or GitHub from env.",
    )
    c.add_argument("--output-dir",  dest="output_dir", default="reports",
                   help="Where to write HTML reports (publish as CI artifacts)")
    c.add_argument("--values-file", dest="values_file", default="values.yaml",
                   help="Values filename next to each changed Chart.yaml")
    c.add_argument("--fail-on",     dest="fail_on", default="none",
                   choices=["none", "critical", "high", "medium", "safe"],
                   help="Exit 1 when changes at this severity or above are found")
    c.add_argument("--path",        default=".", help="Directory to search for bumps")
    c.add_argument("--base-ref",    dest="base_ref", default=None,
                   help="Override base ref (else derived from CI env)")
    c.add_argument("--head-ref",    dest="head_ref", default=None,
                   help="Override head ref (else derived from CI env)")
    c.add_argument("--no-comment",  dest="no_comment", action="store_true",
                   help="Generate reports but don't post an MR/PR comment")

    return parser


def main():
    parser = _build_parser()
    args   = parser.parse_args()

    if args.command == "analyze":
        sys.exit(asyncio.run(_cmd_analyze(args)))
    elif args.command == "detect-bump":
        sys.exit(_cmd_detect_bump(args))
    elif args.command == "ci":
        sys.exit(asyncio.run(_cmd_ci(args)))


if __name__ == "__main__":
    main()
