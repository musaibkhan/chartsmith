EXIT_PASS    = 0
EXIT_BLOCKED = 1
EXIT_ERROR   = 2

_SEVERITY_ORDER = {"critical": 0, "high": 1, "medium": 2, "safe": 3}
_SEV_EMOJI      = {"critical": "🔴", "high": "🟠", "medium": "🟡", "safe": "🟢"}
_MAX_DIFF_LINES = 120   # cap per-resource diff so a big upgrade stays readable


def _unified_diff(old_yaml: str, new_yaml: str) -> str:
    """Unified diff of two rendered manifests, with the +++/--- header stripped."""
    old_lines = (old_yaml or "").splitlines()
    new_lines = (new_yaml or "").splitlines()
    raw  = difflib.unified_diff(old_lines, new_lines, lineterm="", n=2)
    body = [ln for ln in raw if not ln.startswith(("---", "+++"))]
    if len(body) > _MAX_DIFF_LINES:
        hidden = len(body) - _MAX_DIFF_LINES
        body = body[:_MAX_DIFF_LINES] + [f"... ({hidden} more diff lines truncated)"]
    return "\n".join(body)


_RISK_EMOJI = {"CRITICAL": "🔴", "HIGH": "🟠", "MEDIUM": "🟡", "LOW": "🟢"}


def _risk_label(stats: dict) -> str:
    if stats["critical"]:
        return "CRITICAL"
    if stats["high"]:
        return "HIGH"
    if stats["medium"]:
        return "MEDIUM"
    return "LOW"


def _blocked(changes: list[dict], fail_on: str) -> bool:
    if fail_on == "none":
        return False
    threshold = _SEVERITY_ORDER.get(fail_on, 99)
    return any(_SEVERITY_ORDER.get(c["severity"], 99) <= threshold for c in changes)


def _format_markdown(
    chart: str,
    from_v: str,
    to_v: str,
    stats: dict,
    changes: list[dict],
    fail_on: str,
) -> str:
    total = stats["total_changes"]
    _r    = _risk_label(stats)
    risk  = f"{_RISK_EMOJI[_r]} {_r}"
    badges = " · ".join(
        f"{_SEV_EMOJI[s]} {stats[s]} {s}"
        for s in ("critical", "high", "medium", "safe")
        if stats[s]
    )

    lines = [
        f"## ChartSmith: `{chart}` · `{from_v}` → `{to_v}`",
        "",
        f"**Risk: {risk}**" + (f" · {badges}" if badges else "") + f" · {total} change(s)",
        "",
    ]

    if total == 0:
        lines.append("✅ No manifest changes detected between these versions.")
        return "\n".join(lines)

    lines += [
        "| # | Severity | Kind | Name | Change |",
        "|---|----------|------|------|--------|",
    ]
    for i, c in enumerate(changes, 1):
        emoji = _SEV_EMOJI.get(c["severity"], "⚪")
        lines.append(
            f"| {i} | {emoji} {c['severity'].upper()} "
            f"| {c['kind']} | `{c['name']}` | {c['change_type']} |"
        )

    detailed = [c for c in changes if c["severity"] in ("critical", "high")]
    if detailed:
        lines += ["", "### Critical & High — diffs", ""]
        for c in detailed:
            emoji = _SEV_EMOJI.get(c["severity"], "")
            lines += [
                "<details>",
                f"<summary>{emoji} <code>{c['kind']}/{c['name']}</code> — "
                f"{c['change_type'].upper()}{(' · ' + c['note']) if c.get('note') else ''}</summary>",
                "",
            ]
            if c.get("action"):
                lines += [f"> ⚡ **Action needed:** {c['action']}", ""]
            diff_text = _unified_diff(c.get("old_yaml", ""), c.get("new_yaml", ""))
            if diff_text:
                lines += ["```diff", diff_text, "```"]
            else:
                lines.append("_(no line-level differences captured)_")
            lines += ["", "</details>", ""]

    lines.append("")
    if fail_on == "none":
        lines.append("ℹ️ **Informational** — no merge gate set (`fail-on: none`).")
    elif _blocked(changes, fail_on):
        lines.append(
            f"⛔ **Blocked** — `{fail_on}`+ severity changes present. "
            "Review required before merging."
        )
    else:
        lines.append(
            f"✅ **Pass** — nothing at `{fail_on}` severity or above."
        )

    lines += ["", "---", "*Generated by [ChartSmith](https://github.com/your-org/chartsmith)*"]
    return "\n".join(lines)


_HTML_DIFF_MAX = 400  # generous on a full page

_SEV_HEX = {"critical": "#FF5C7A", "high": "#FF6B2C", "medium": "#FFC857", "safe": "#3DDC97"}
_CHG_HEX = {"added": "#3DDC97", "removed": "#FF5C7A", "modified": "#A78BFA", "deprecated_api": "#FF6B2C"}


def _html_diff(old_yaml: str, new_yaml: str) -> str:
    import html as _html
    old_lines = (old_yaml or "").splitlines()
    new_lines = (new_yaml or "").splitlines()
    rows, count = [], 0
    for ln in difflib.unified_diff(old_lines, new_lines, lineterm="", n=3):
        if ln.startswith(("---", "+++")):
            continue
        if count >= _HTML_DIFF_MAX:
            rows.append('<div class="dl ctx">… (diff truncated)</div>')
            break
        cls = ("add" if ln.startswith("+") else
               "rem" if ln.startswith("-") else
               "meta" if ln.startswith("@@") else "ctx")
        rows.append(f'<div class="dl {cls}">{_html.escape(ln) or "&nbsp;"}</div>')
        count += 1
    return "".join(rows)


